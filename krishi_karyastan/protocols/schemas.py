"""Typed message payload schemas for observations, alerts, proposals, and reservations."""

from __future__ import annotations
import uuid
from enum import Enum
from typing import Dict, List, Optional
from pydantic import BaseModel, Field
from krishi_karyastan.core.models import Coordinates, SoilNutrientProfile, TimeSlot


class AlertUrgency(str, Enum):
    """Urgency level for flagged agronomic deficits."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class SoilObservationReport(BaseModel):
    """Observation payload sent from a sensing agent to the Shared Knowledge Base."""
    coords: Coordinates
    moisture_pct: float
    nutrients: SoilNutrientProfile
    crop_stage: str
    pest_index: float
    confidence: float = Field(default=0.9, ge=0.0, le=1.0)
    agent_id: str
    sensor_tick: int


class SoilDeficiencyAlert(BaseModel):
    """Flagged by the Soil Monitoring Agent when a sector exhibits dry, nutrient-poor symptoms."""
    alert_id: str = Field(default_factory=lambda: f"alert_{uuid.uuid4().hex[:8]}")
    coords: Coordinates
    current_moisture_pct: float
    target_moisture_pct: float = Field(default=50.0)
    moisture_deficit_pct: float
    current_nitrogen_ppm: float
    target_nitrogen_ppm: float = Field(default=120.0)
    nitrogen_deficit_ppm: float
    current_phosphorus_ppm: float
    current_potassium_ppm: float
    field_capacity_pct: float = Field(default=65.0)
    saturation_limit_pct: float = Field(default=75.0)
    urgency: AlertUrgency = Field(default=AlertUrgency.HIGH)
    flagged_by: str
    tick: int

    @classmethod
    def create_from_reading(
        cls,
        coords: Coordinates,
        moisture: float,
        nitrogen: float,
        phosphorus: float,
        potassium: float,
        flagged_by: str,
        tick: int,
        target_moisture: float = 50.0,
        target_nitrogen: float = 120.0,
    ) -> SoilDeficiencyAlert:
        m_def = max(0.0, target_moisture - moisture)
        n_def = max(0.0, target_nitrogen - nitrogen)

        urgency = AlertUrgency.LOW
        if m_def > 25.0 or n_def > 60.0:
            urgency = AlertUrgency.CRITICAL
        elif m_def > 15.0 or n_def > 35.0:
            urgency = AlertUrgency.HIGH
        elif m_def > 5.0 or n_def > 15.0:
            urgency = AlertUrgency.MEDIUM

        return cls(
            coords=coords,
            current_moisture_pct=round(moisture, 2),
            target_moisture_pct=target_moisture,
            moisture_deficit_pct=round(m_def, 2),
            current_nitrogen_ppm=round(nitrogen, 2),
            target_nitrogen_ppm=target_nitrogen,
            nitrogen_deficit_ppm=round(n_def, 2),
            current_phosphorus_ppm=round(phosphorus, 2),
            current_potassium_ppm=round(potassium, 2),
            urgency=urgency,
            flagged_by=flagged_by,
            tick=tick,
        )


class CFPFertigation(BaseModel):
    """Call For Proposals: Requests cooperative intervention from Irrigation & Fertilizer agents."""
    cfp_id: str = Field(default_factory=lambda: f"cfp_{uuid.uuid4().hex[:8]}")
    target_coords: Coordinates
    alert: SoilDeficiencyAlert
    max_safe_moisture_pct: float = Field(default=60.0, description="Strict agronomic threshold to prevent over-saturation")
    deadline_tick: int


class IrrigationProposal(BaseModel):
    """Proposal generated by Irrigation Agent specifying water dosage and required time window."""
    proposal_id: str = Field(default_factory=lambda: f"prop_irr_{uuid.uuid4().hex[:6]}")
    agent_id: str
    target_coords: Coordinates
    water_volume_liters: float
    estimated_moisture_gain_pct: float
    time_slot: TimeSlot
    water_flow_rate_lpm: float = Field(default=5.0)
    energy_cost: float = Field(default=1.0)


class FertilizerProposal(BaseModel):
    """Proposal generated by Fertilizer Agent specifying NPK dosage, carrier fluid, and time window."""
    proposal_id: str = Field(default_factory=lambda: f"prop_fert_{uuid.uuid4().hex[:6]}")
    agent_id: str
    target_coords: Coordinates
    nitrogen_dose_g: float
    phosphorus_dose_g: float
    potassium_dose_g: float
    carrier_fluid_liters: float
    carrier_moisture_gain_pct: float
    time_slot: TimeSlot
    energy_cost: float = Field(default=1.2)


class CoordinatedFertigationSchedule(BaseModel):
    """Synthesized joint response schedule negotiated between Irrigation and Fertilizer agents."""
    schedule_id: str = Field(default_factory=lambda: f"sched_{uuid.uuid4().hex[:8]}")
    target_coords: Coordinates
    fertilizer_agent_id: str
    fertilizer_slot: TimeSlot
    nitrogen_dose_g: float
    carrier_fluid_liters: float
    carrier_moisture_gain_pct: float

    irrigation_agent_id: str
    irrigation_slot: TimeSlot
    irrigation_volume_liters: float
    irrigation_moisture_gain_pct: float

    initial_moisture_pct: float
    projected_final_moisture_pct: float
    saturation_threshold_pct: float
    is_safe_non_saturated: bool
    is_collision_free: bool
    negotiation_notes: List[str] = Field(default_factory=list)


class ReservationRequest(BaseModel):
    """Space-time coordinate reservation to guarantee collision-free field movement."""
    request_id: str = Field(default_factory=lambda: f"res_{uuid.uuid4().hex[:6]}")
    agent_id: str
    coords: Coordinates
    time_slot: TimeSlot
    reason: str = Field(default="Field Task Execution")


class ReservationResponse(BaseModel):
    """Response from Spatio-Temporal collision governor."""
    request_id: str
    agent_id: str
    coords: Coordinates
    time_slot: TimeSlot
    granted: bool
    conflicting_agent: Optional[str] = None
    suggested_alternative_slot: Optional[TimeSlot] = None
    message: str = "Reservation approved"
